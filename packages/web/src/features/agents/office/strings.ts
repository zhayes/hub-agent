const dictionaries: Record<Locale, Record<OfficeKey, string>> = {
  'en-US': en,
  'zh-CN': zh,
}

export type OfficeTranslate = (
  key: OfficeKey,
  params?: Readonly<Record<string, string | number>>,
) => string

export function officeT(locale: Locale): OfficeTranslate {
  const dictionary = dictionaries[isLocale(locale) ? locale : 'en-US']
  return (key, params = {}) =>
    (dictionary[key] ?? en[key]).replace(/\{([^}]+)\}/g, (_, name: string) =>
      String(params[name] ?? `{${name}}`),
    )
}
